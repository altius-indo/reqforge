"""Generate a GitHub Actions pipeline driven by the eval registry.

The workflow is stage-shaped (traceability gate -> commit -> acceptance/security ->
performance -> deploy -> post-deploy, plus a scheduled monitor) and each stage job
asks reqforge which evals belong to it at run time. Adding an eval to a story
therefore extends CI/CD without regenerating the workflow."""
from __future__ import annotations

import shutil
from pathlib import Path

PKG_DIR = Path(__file__).resolve().parent


def _indent(lines: list[str], n: int) -> str:
    return "\n".join(" " * n + ln for ln in lines)


def workflow(store, requirements_path: str = "") -> str:
    cfg = store.config.get("cicd", {})
    py = cfg.get("python", "3.12")
    req_repo = cfg.get("requirements_repo", "")
    setup = cfg.get("setup_steps", [])
    deploy_cmd = cfg.get("deploy_command") or "echo 'set cicd.deploy_command in reqforge.json' && exit 1"
    cron = cfg.get("monitor_cron", "*/30 * * * *")
    req_dir = ".requirements" if req_repo else (requirements_path or "requirements-repo")

    checkout = ["- uses: actions/checkout@v4"]
    if req_repo:
        checkout += [
            "- uses: actions/checkout@v4",
            "  with:",
            f"    repository: {req_repo}",
            "    path: .requirements",
            "    token: ${{ secrets.REQFORGE_REPO_TOKEN || github.token }}",
        ]
    checkout += [f"- uses: actions/setup-python@v5", "  with:", f"    python-version: '{py}'"]
    setup_steps = [f"- run: {s}" for s in setup]

    def stage_job(name, stage, needs, cond=None, env_name=None):
        lines = [f"{name}:", "  runs-on: ubuntu-latest"]
        if needs:
            lines.append(f"  needs: [{', '.join(needs)}]")
        if cond:
            lines.append(f"  if: {cond}")
        if env_name:
            lines.append(f"  environment: {env_name}")
        lines += ["  steps:", _indent(checkout + setup_steps, 4),
                  f"    - name: Run {stage} evals",
                  f"      run: python -m reqforge evals run --stage {stage} --workdir . --md >> \"$GITHUB_STEP_SUMMARY\"",
                  "    - uses: actions/upload-artifact@v4",
                  "      if: always()",
                  "      with:",
                  f"        name: reqforge-{stage}",
                  "        path: reqforge-reports/"]
        return lines

    on_main = "github.event_name == 'push' && github.ref == 'refs/heads/main'"
    not_sched = "github.event_name != 'schedule'"
    jobs: list[str] = []
    jobs += ["traceability:", "  runs-on: ubuntu-latest", f"  if: {not_sched}", "  steps:",
             _indent(checkout, 4),
             "    - name: Requirement lint (MECE + quality)",
             "      run: python -m reqforge lint --md --gate >> \"$GITHUB_STEP_SUMMARY\"",
             "    - name: Traceability gate (requirement -> story -> eval)",
             "      run: python -m reqforge trace --md --gate >> \"$GITHUB_STEP_SUMMARY\""]
    jobs += stage_job("commit", "commit", ["traceability"])
    jobs += stage_job("acceptance", "acceptance", ["commit"])
    jobs += stage_job("security", "security", ["commit"])
    jobs += stage_job("performance", "performance", ["acceptance"], cond=on_main)
    jobs += ["deploy:", "  runs-on: ubuntu-latest", "  needs: [acceptance, security, performance]",
             f"  if: {on_main}", "  environment: production", "  steps:",
             _indent(checkout + setup_steps, 4),
             "    - name: Deploy",
             f"      run: {deploy_cmd}"]
    jobs += stage_job("post-deploy", "post-deploy", ["deploy"], cond=on_main)
    jobs += stage_job("monitor", "monitor", [],
                      cond="github.event_name == 'schedule' || github.event_name == 'workflow_dispatch'")

    return "\n".join([
        "# Generated by reqforge. Stage membership comes from story evals at run time:",
        "# add evals to stories (reqforge / UI / API) instead of editing this file.",
        "name: reqforge-pipeline",
        "on:",
        "  push:",
        "    branches: [main]",
        "  pull_request:",
        "  workflow_dispatch:",
        "  schedule:",
        f"    - cron: '{cron}'",
        "permissions:",
        "  contents: read",
        "env:",
        "  PYTHONPATH: .reqforge",
        f"  REQFORGE_REPO: {req_dir}",
        "concurrency:",
        "  group: reqforge-${{ github.ref }}",
        "  cancel-in-progress: ${{ github.event_name == 'pull_request' }}",
        "jobs:",
        _indent(jobs, 2),
        "",
    ])


def generate(store, out_dir: str, requirements_path: str = "", vendor: bool = True) -> list[str]:
    out = Path(out_dir).resolve()
    wf = out / ".github" / "workflows" / "reqforge-pipeline.yml"
    wf.parent.mkdir(parents=True, exist_ok=True)
    if not requirements_path and not store.config.get("cicd", {}).get("requirements_repo"):
        try:
            requirements_path = str(store.root.relative_to(out)) or "."
        except ValueError:
            raise ValueError("requirements repo is outside the code repo: set cicd.requirements_repo "
                             "(owner/name) in reqforge.json or pass --requirements-path") from None
    wf.write_text(workflow(store, requirements_path))
    written = [str(wf)]
    if vendor:  # stdlib-only package: copy it so CI needs no install step
        dest = out / ".reqforge" / "reqforge"
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(PKG_DIR, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        written.append(str(dest))
    return written
